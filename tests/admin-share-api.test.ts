import test from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {report,testDatabase} from './helpers/data-fixtures';
import {shareEnDraft} from './helpers/shareen-fixture';

test('admin sharing authenticates cached reads and bounds same-origin mutations',async()=>{
 const ctx=await testDatabase();
 const oldHash=process.env.WCCAT_ADMIN_PASSWORD_HASH,oldSecret=process.env.WCCAT_ADMIN_SESSION_SECRET,oldKey=process.env.DEEPSEEK_API_KEY,oldFetch=globalThis.fetch;
 process.env.DEEPSEEK_API_KEY='';
 let aiCalls=0;
 globalThis.fetch=async()=>{aiCalls++;throw new Error('Simulated model outage; network disabled');};
 try{
  const auth=await import('../src/lib/admin-auth');
  process.env.WCCAT_ADMIN_PASSWORD_HASH=auth.hashAdminPassword('test-only-admin-password');
  process.env.WCCAT_ADMIN_SESSION_SECRET='test-only-session-secret-32-or-more-characters';
  const {GET,POST}=await import('../src/app/api/admin/share/route');
  const {createJob,getJob,runJob}=await import('../src/lib/admin-jobs');
  const {readJobLogs}=await import('../src/lib/admin-job-logs');
  const original=report('2025-09-01');ctx.saveDailyReportToDb(original);
  const cookie='wccat_admin='+auth.createAdminSession();
  const get=(date:string,loggedIn=true)=>GET(new Request('https://example.test/api/admin/share?date='+date,{headers:loggedIn?{cookie}:{}}));
  const post=(body:unknown,origin='https://example.test',loggedIn=true)=>POST(new Request('https://example.test/api/admin/share',{method:'POST',headers:{...(loggedIn?{cookie}:{}),origin,'content-type':'application/json'},body:JSON.stringify(body)}));
  assert.equal((await get('2025-09-01',false)).status,401);
  assert.equal((await post({action:'generate',date:'2025-09-01'},undefined,false)).status,401);
  assert.equal((await post({action:'save',date:'2025-09-01',copy:{}},'https://evil.test')).status,403);
  assert.equal((await post({action:'generate',date:'2025-09-01'},'https://evil.test')).status,403);
  const cached=await get('2025-09-01');
  assert.equal(cached.status,200);assert.equal(cached.headers.get('cache-control'),'no-store');
  const cachedPayload=await cached.json();
  assert.deepEqual(cachedPayload.report,original);
  assert.match(cachedPayload.shareEnRevision,/^[a-f0-9]{64}$/);assert.equal(aiCalls,0);
  assert.equal((await get('2026-02-30')).status,400);
  assert.equal((await get('2025-09-02')).status,404);
  assert.equal((await post({action:'generate',date:'2025-09-02'})).status,404);
  assert.equal((await post({action:'generate',date:'2026-02-30'})).status,400);
  assert.equal((await post({action:'generate',date:'2025-09-01',format:'other'})).status,400);
  assert.equal((await post({action:'generate',date:'2025-09-01',force:'true'})).status,400);
  assert.equal((await post({action:'save',date:'2025-09-01',copy:{},expectedRevision:cachedPayload.shareEnRevision})).status,400);
  assert.equal((await post({action:'save',date:'2025-09-01',copy:'x'.repeat(128*1024)})).status,413);
  const editable=report('2025-09-03');
  editable.topics.push({...editable.topics[0],id:'topic-two',rank:2});
  ctx.saveDailyReportToDb(editable);
  const {sourceFingerprint}=await import('../src/lib/shareen');
  const draft=shareEnDraft(editable);
  const copy={...draft,version:1,generatedAt:editable.generatedAt,model:'test',sourceFingerprint:sourceFingerprint(editable),posts:draft.posts.map(p=>({...p,text:`WcCAT Daily Hot\n\n${p.text}\n\n${draft.top3.map((t,i)=>`${['1️⃣','2️⃣','3️⃣'][i]} ${t.summary}`).join('\n')}\n\nWcCAT: read the cards.`}))};
  copy.overview.headline='Edited admin sharing headline';
  const editorPayload=await (await get('2025-09-03')).json();
  const expectedRevision=editorPayload.shareEnRevision;
  assert.equal((await post({action:'save',date:'2025-09-03',copy})).status,400,'manual saves require the editor revision');
  assert.equal((await post({action:'save',date:'2025-09-03',copy,expectedRevision:'x'.repeat(129)})).status,400);
  const edited=await post({action:'save',date:'2025-09-03',copy,expectedRevision});
  assert.equal(edited.status,200);
  const editedPayload=await edited.json();
  assert.equal(editedPayload.report.shareEn.overview.headline,copy.overview.headline);
  assert.match(editedPayload.shareEnRevision,/^[a-f0-9]{64}$/);
  assert.notEqual(editedPayload.shareEnRevision,expectedRevision);
  assert.equal(ctx.readDailyReportFromDb('2025-09-03')?.headline,editable.headline);
  const stale=await post({action:'save',date:'2025-09-03',copy:{...copy,overview:{...copy.overview,headline:'Stale editor headline'}},expectedRevision});
  assert.equal(stale.status,409,'a stale tab cannot overwrite a newer edit for the same Chinese report');
  assert.match((await stale.json()).error,/载入最新版本/);
  assert.equal(ctx.readDailyReportFromDb('2025-09-03')?.shareEn?.overview.headline,copy.overview.headline);
  assert.equal((await post({action:'save',date:'2025-09-03',copy:{...copy,sourceFingerprint:'stale'},expectedRevision:editedPayload.shareEnRevision})).status,400);
  assert.equal(aiCalls,0,'manual edits never call AI');
  assert.throws(()=>createJob({kind:'sharing',reportDate:'2025-09-02',shareFormat:'all'}),/日报/);
  // Running seeded tasks in-process keeps AI stubs and the temporary DB under test control.
  const seed=(format:'english'|'shareen',force=false)=>{
   const id=randomUUID(),now=Date.now();
   ctx.getDb().prepare("insert into admin_jobs(id,kind,status,input,created_at,updated_at) values(?,'sharing','queued',?,?,?)").run(id,JSON.stringify({kind:'sharing',reportDate:'2025-09-01',shareFormat:format,force}),now,now);
   return id;
  };
  const complete=await runJob(seed('english'));
  assert.equal(complete.status,'complete',complete.error??undefined);
  assert.equal(complete.result.sharing?.englishReady,true);
  assert.ok(readJobLogs(complete.id).entries.length>0);
  const partial=await runJob(seed('shareen'));
  assert.equal(partial.status,'partial',partial.error??undefined);
  assert.equal(partial.result.sharing?.shareEnReady,false);
  assert.deepEqual(ctx.readDailyReportFromDb('2025-09-01')?.shareEnglish,original.shareEnglish);
  assert.equal(aiCalls,0);
  process.env.DEEPSEEK_API_KEY='test-only-no-network-sharing-key';
  const forcedInProcess=await runJob(seed('english',true));
  assert.ok(aiCalls>0,'force regeneration bypasses a saved English translation');
  assert.equal(forcedInProcess.result.sharing?.englishReady,true,'a failed regeneration retains saved English');
  assert.equal(forcedInProcess.status,'partial','a failed refresh must not claim a newly completed generation');
  process.env.DEEPSEEK_API_KEY='';
  const removedReportId=seed('english');
  ctx.getDb().prepare('delete from daily_reports where report_date=?').run(original.reportDate);
  const failed=await runJob(removedReportId);
  assert.equal(failed.status,'failed','a report removed after enqueue cannot generate sharing');
  assert.equal(readJobLogs(failed.id).entries.at(-1)?.level,'error');
  ctx.saveDailyReportToDb(original);
  // The serial job lock must cover sharing and the other maintenance tasks.
  const queuedId=seed('english');
  assert.throws(()=>createJob({kind:'sharing',reportDate:'2025-09-01',shareFormat:'all',force:true}),/后台任务/);
  ctx.getDb().prepare("update admin_jobs set status='complete' where id=?").run(queuedId);
  const forced=await post({action:'generate',date:'2025-09-01',format:'english',force:true});
  assert.equal(forced.status,202);
  const forcedJob=(await forced.json()).job;
  assert.equal(forcedJob.input.force,true);assert.equal(forcedJob.input.shareFormat,'english');
  let done=getJob(forcedJob.id);
  for(let i=0;i<200&&['queued','running'].includes(done.status);i++){await new Promise(resolve=>setTimeout(resolve,30));done=getJob(done.id);}
  assert.ok(!['queued','running'].includes(done.status));
 }finally{
  globalThis.fetch=oldFetch;
  for(const [name,value] of Object.entries({WCCAT_ADMIN_PASSWORD_HASH:oldHash,WCCAT_ADMIN_SESSION_SECRET:oldSecret,DEEPSEEK_API_KEY:oldKey}))if(value===undefined)delete process.env[name];else process.env[name]=value;
  ctx.close();
 }
});
